"""The allophone durations the chip really produces, as 6502 data.

Measured out of the emulation with pp2_render -q, not read off the data sheet:
the sheet is nominal for a real chip and the emulation plays the AL2 ROM's own
frame repeat counts, which are up to 45% shorter.  Stored in quarter
milliseconds, 16-bit, because the longest is 291 ms and the animation adds them
up over a whole sentence -- rounding to 2 ms a time would wander.
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)
RATE = 11025.0
samples = [int(l) for l in open('allo_samples.txt')]
assert len(samples) == 64
q = [int(round(s / RATE * 4000.0)) for s in samples]
assert max(q) < 4096, max(q)

names = [l.split()[0][3:] for l in open('allophones.txt') if l.startswith('SP_')]
with open(os.path.join(HERE, '..', 'src', 'durdata.inc'), 'w') as f:
    f.write('; Generated by mkdur_a2.py -- do not edit.\n'
            '; Allophone durations in quarter milliseconds, measured from the\n'
            '; emulation (pp2_render -q), not from the data sheet.\n\n')
    f.write('allo_dur4:              ; low bytes\n')
    for j in range(0, 64, 8):
        f.write('        .byte ' + ','.join('<%d' % v for v in q[j:j + 8])
                + '   ; ' + ' '.join(names[j:j + 8]) + '\n')
    f.write('\nallo_dur4h:             ; high bytes\n')
    for j in range(0, 64, 8):
        f.write('        .byte ' + ','.join('>%d' % v for v in q[j:j + 8]) + '\n')
print('durations: %d..%d quarter-ms (%.0f..%.0f ms)'
      % (min(q), max(q), min(q) / 4.0, max(q) / 4.0))
