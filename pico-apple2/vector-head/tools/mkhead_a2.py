"""Emit the vector head for the Apple II, as ca65 source.

Reuses mkhead.py whole -- the 1985 model, the moving-group anchoring, the ten
visemes -- and changes only the target. The CPC lays the head out at x=159 in
320x200 with a text window down the right; HGR mixed mode gives four text lines
at the BOTTOM for free, so here the head gets the full width and 160 rows.

Coordinates are stored the way the CPC stores them, and for the same reason:
dx from the mirror line plus a row, both one byte. x = CX +/- dx, so the whole
head is one half-face drawn twice.
"""
import importlib.util, io, contextlib, os, sys

# mkhead.py is the CPC project's -- the 1985 model, the moving groups and the
# ten shapes all come from there, unchanged:
#   https://github.com/lambdamikel/animated-speaking-cpc-vector-head
# Point MKHEAD at src/mkhead.py there, or drop it in beside this script.  The
# generated .inc files are committed, so this is only needed to re-derive the
# head, not to build it.
HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)
MKHEAD = os.environ.get('MKHEAD', 'mkhead.py')
if not os.path.exists(MKHEAD):
    sys.exit('mkhead.py not found.\n'
             '  git clone https://github.com/lambdamikel/'
             'animated-speaking-cpc-vector-head\n'
             '  MKHEAD=.../src/mkhead.py python3 mkhead_a2.py\n'
             'src/headdata_a2.inc is already generated, so this is only '
             'needed to re-derive the head.')

spec = importlib.util.spec_from_file_location('mk', MKHEAD)
mk = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(mk)

W, H, CX = 280, 160, 140
A2_PIXEL_AR = (4.0/280) / (3.0/192)

xs = [x for p in mk.polys for x, y in p]
ys = [y for p in mk.polys for x, y in p]
x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
full_w, model_h = 2.0*max(abs(x1), abs(x0)), y1 - y0
sy = (H - 4) / model_h
sx = sy / A2_PIXEL_AR
if full_w*sx > W - 4:
    sx = (W - 4)/full_w; sy = sx*A2_PIXEL_AR

def a2(x, y):
    """model -> (dx from the mirror line, HGR row)"""
    return int(round(x*sx)), int(round((H - 2) - (y - y0)*sy))

def emit(f, label, polylines, comment=''):
    """count, then dx/row pairs, zero-terminated -- as headdata.inc does."""
    n = 0
    f.write('%s:%s\n' % (label, ('              ; ' + comment) if comment else ''))
    for p in polylines:
        pts = [a2(x, y) for x, y in p]
        if len(pts) < 2:
            continue
        f.write('        .byte %d\n' % len(pts))
        for j in range(0, len(pts), 6):
            f.write('        .byte ' + ','.join('%d,%d' % t for t in pts[j:j+6]) + '\n')
        n += len(pts) - 1
    f.write('        .byte 0\n\n')
    return n

names = [l.split()[0][3:] for l in open('allophones.txt') if l.startswith('SP_')]
vnames = [v[0] for v in mk.VISEMES]
enames = [e[0] for e in mk.EYES]

with open(os.path.join(HERE, '..', 'src', 'headdata_a2.inc'), 'w') as f:
    f.write('; Generated by mkhead_a2.py -- do not edit.\n'
            '; The 1985 digitised head for the Apple II, HGR mixed mode.\n'
            '; Coordinates are (dx from x=%d, row); mirror about that line.\n\n'
            'HEAD_CX = %d\nHEAD_W  = %d\nHEAD_H  = %d\n'
            'NVISEME = %d\nNEYE    = %d\n\n'
            % (CX, CX, W, H, len(vnames), len(enames)))

    nstat = emit(f, 'head_static', mk.static, 'drawn once, never moves')

    nmouth = 0
    for nm, shape in zip(vnames, mk.shapes[0]):
        nmouth += emit(f, 'mouth_%s' % nm, shape, 'viseme: %s' % nm)
    f.write('mouth_tab:\n')
    for j in range(0, len(vnames), 4):
        f.write('        .addr ' + ','.join('mouth_%s' % n for n in vnames[j:j+4]) + '\n')
    f.write('\n')

    # mkhead.py has two moving groups, not one: GROUPS = [(MOUTH+CHIN), (EYE)].
    # Both are cut out of `static`, so emitting only shapes[0] left the eye
    # sockets with nothing drawn in them at all -- blank holes in the face.
    neye = 0
    for nm, shape in zip(enames, mk.shapes[1]):
        neye += emit(f, 'eye_%s' % nm, shape, 'eyes: %s' % nm)
    f.write('eye_tab:\n        .addr ' +
            ','.join('eye_%s' % n for n in enames) + '\n\n')

    f.write('; allophone -> viseme index\nallo_viseme:\n')
    for j in range(0, 64, 8):
        f.write('        .byte ' + ','.join(str(mk.VMAP[k]) for k in range(j, j+8))
                + '   ; %s\n' % ' '.join(names[j:j+8]))
    # Durations run to 420 ms, which does not fit a byte -- store them in
    # units of 2 ms instead (0..210). Two milliseconds is far finer than a
    # viseme change can be seen at, and it keeps the table 64 bytes.
    f.write('\n; allophone -> duration, in units of 2 ms (data sheet)\n'
            'ALLO_MS_UNIT = 2\nallo_dur2:\n')
    for j in range(0, 64, 8):
        f.write('        .byte ' + ','.join(str(round(mk.DUR[k]/2)) for k in range(j, j+8))
                + '   ; %s\n' % ' '.join('%dms' % mk.DUR[k] for k in range(j, j+8)))
    assert max(mk.DUR.values()) <= 255*2, 'duration overflows even at 2 ms units' 

print('head: %d static segments, %d mouth segments over %d shapes, '
      '%d eye segments over %d'
      % (nstat, nmouth, len(vnames), neye, len(enames)))
print('scale sx=%.3f sy=%.3f -> %d x %d px, dx max %d'
      % (sx, sy, round(full_w*sx), round(model_h*sy),
         max(abs(a2(x, y)[0]) for x, y in zip(xs, ys))))
print('src/headdata_a2.inc: %d bytes of source'
      % os.path.getsize(os.path.join(HERE, '..', 'src', 'headdata_a2.inc')))
